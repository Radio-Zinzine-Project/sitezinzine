    public function testAddAndRemoveUsers(): void
    {
        $emission = new Emission();

        $user1 = $this->createMock(User::class);
        $user2 = $this->createMock(User::class);

        $emission->addUser($user1);
        $emission->addUser($user2);

        $this->assertCount(2, $emission->getUsers());
        $this->assertTrue($emission->getUsers()->contains($user1));
        $this->assertTrue($emission->getUsers()->contains($user2));

        $emission->removeUser($user1);

        $this->assertCount(1, $emission->getUsers());
        $this->assertFalse($emission->getUsers()->contains($user1));
        $this->assertTrue($emission->getUsers()->contains($user2));
    }

