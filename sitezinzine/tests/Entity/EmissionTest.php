    public function testBasicSettersAndGetters(): void
    {
        $emission = new Emission();

        $datepub = new \DateTime('2023-01-01 12:00:00');
        $updatedAt = new \DateTime('2023-02-01 14:30:00');

        $emission
            ->setTitre('Titre test')
            ->setKeyword('motclé')
            ->setDatepub($datepub)
            ->setRef('REF-123')
            ->setDuree(150)
            ->setUrl('https://example.com/audio.mp3')
            ->setDescriptif('Une belle description')
            ->setThumbnail('image.jpg')
            ->setThumbnailMp3('audio.mp3')
            ->setUpdatedat($updatedAt);

        $this->assertSame('Titre test', $emission->getTitre());
        $this->assertSame('motclé', $emission->getKeyword());
        $this->assertSame($datepub, $emission->getDatepub());
        $this->assertSame('REF-123', $emission->getRef());
        $this->assertSame(150, $emission->getDuree());
        $this->assertSame(
            'https://example.com/audio.mp3',
            $emission->getUrl()
        );
        $this->assertSame(
            'Une belle description',
            $emission->getDescriptif()
        );
        $this->assertSame('image.jpg', $emission->getThumbnail());
        $this->assertSame('audio.mp3', $emission->getThumbnailMp3());
        $this->assertSame($updatedAt, $emission->getUpdatedat());
    }

