    public function testRemoveDiffusionClearsOwningSide(): void
    {
        $emission = new Emission();

        $diffusion = $this->createMock(Diffusion::class);

        $diffusion
            ->expects($this->exactly(2))
            ->method('setEmission')
            ->withConsecutive(
                [$emission],
                [null]
            );

        $diffusion
            ->expects($this->once())
            ->method('getEmission')
            ->willReturn($emission);

        $emission->addDiffusion($diffusion);
        $emission->removeDiffusion($diffusion);

        $this->assertCount(0, $emission->getDiffusions());
    }

