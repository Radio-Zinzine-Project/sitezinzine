    public function testSoftDeleteAndRestore(): void
    {
        $emission = new Emission();

        $this->assertFalse($emission->isDeleted());
        $this->assertNull($emission->getDeletedAt());

        $result = $emission->softDelete();

        $this->assertSame($emission, $result);
        $this->assertTrue($emission->isDeleted());
        $this->assertInstanceOf(
            \DateTimeImmutable::class,
            $emission->getDeletedAt()
        );

        $result = $emission->restore();

        $this->assertSame($emission, $result);
        $this->assertFalse($emission->isDeleted());
        $this->assertNull($emission->getDeletedAt());
    }

