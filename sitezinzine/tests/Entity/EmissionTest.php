    public function testValidationAddsViolationsWithoutUserOrFormerHost(): void
    {
        $emission = new Emission();

        $context = $this->createMock(
            ExecutionContextInterface::class
        );

        $builderUsers = $this->createMock(
            ConstraintViolationBuilderInterface::class
        );

        $builderInvites = $this->createMock(
            ConstraintViolationBuilderInterface::class
        );

        $message =
            'Il faut sélectionner au moins un·e utilisateur·ice ' .
            'ou un·e ancien·ne animateur·ice.';

        $context
            ->expects($this->exactly(2))
            ->method('buildViolation')
            ->with($message)
            ->willReturnOnConsecutiveCalls(
                $builderUsers,
                $builderInvites
            );

        $builderUsers
            ->expects($this->once())
            ->method('atPath')
            ->with('users')
            ->willReturnSelf();

        $builderUsers
            ->expects($this->once())
            ->method('addViolation');

        $builderInvites
            ->expects($this->once())
            ->method('atPath')
            ->with('inviteOldAnimateurs')
            ->willReturnSelf();

        $builderInvites
            ->expects($this->once())
            ->method('addViolation');

        $emission->validateOwnerOrFormerHost($context);
    }

