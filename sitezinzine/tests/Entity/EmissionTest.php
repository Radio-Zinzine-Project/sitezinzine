    public function testDerniereDiffusionReturnsLatestDate(): void
    {
        $emission = new Emission();

        $date1 = new \DateTime('2026-01-10 10:00:00');
        $date2 = new \DateTime('2026-01-12 14:00:00');
        $date3 = new \DateTime('2026-01-11 18:00:00');

        $diffusion1 = $this->createMock(Diffusion::class);
        $diffusion2 = $this->createMock(Diffusion::class);
        $diffusion3 = $this->createMock(Diffusion::class);

        $diffusion1
            ->method('getHoraireDiffusion')
            ->willReturn($date1);

        $diffusion2
            ->method('getHoraireDiffusion')
            ->willReturn($date2);

        $diffusion3
            ->method('getHoraireDiffusion')
            ->willReturn($date3);

        $diffusion1->method('setEmission');
        $diffusion2->method('setEmission');
        $diffusion3->method('setEmission');

        $emission->addDiffusion($diffusion1);
        $emission->addDiffusion($diffusion2);
        $emission->addDiffusion($diffusion3);

        $this->assertSame(
            $date2,
            $emission->getDerniereDiffusion()
        );
    }

