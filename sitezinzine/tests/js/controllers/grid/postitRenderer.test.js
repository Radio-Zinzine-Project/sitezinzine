import { describe, expect, test } from 'vitest'
import { renderPostitContent } from '../../../../assets/controllers/grid/postitRenderer'
import { getStatusLabel } from '../../../../assets/controllers/grid/sidebar'
import { getConflictSeverityLabel } from '../../../../assets/controllers/grid/conflicts'
import { element } from '../../support/dom'

const context = { getStatusLabel, getConflictSeverityLabel }

describe('Rendu des passages de grille', () => {
    test.each([
        [{ broadcastRank: '1' }, 'postit--first', '■ 1re diff'],
        [{ broadcastRank: '3', emissionIsAutoGenerated: 'true' }, 'postit--rebroadcast', '↺ Rediff 2'],
        [{ isProjectedOverride: 'true' }, 'postit--rescheduled', '↔ Déplacé'],
        [{ emissionIsAutoGenerated: 'true' }, 'postit--live', '● Direct'],
        [{ isManualDraft: 'true', emissionIsAutoGenerated: 'true' }, 'postit--live', '● Direct'],
    ])('la carte reflète le type/rang %j', (data, className, badge) => {
        const postit = element({ slots: '4', categoryTitle: 'Zinzine', ...data })
        renderPostitContent(context, postit, 'Mon émission')
        expect(postit.classList.contains(className)).toBe(true)
        expect(postit.querySelector('.postit__badge').textContent).toBe(badge)
        expect(postit.getAttribute('title')).toContain('Mon émission')
    })

    test('un petit passage garde titre et catégorie sur une ligne sans badges', () => {
        const postit = element({ slots: '2', categorySlug: 'ABC', hasConflict: 'true', conflictSeverity: 'partial', conflictCount: '2' })
        renderPostitContent(context, postit, '<script>titre</script>')
        expect(postit.querySelector('script')).toBeNull()
        expect(postit.querySelector('.postit__label').textContent.trim()).toBe('ABC — <script>titre</script>')
        expect(postit.querySelector('.postit__badge')).toBeNull()
        expect(postit.querySelector('.postit__alert')).toBeNull()
        expect(postit.title).toContain('Conflit partiel (2)')
    })

    test('le changement d’affectation retire les anciennes classes et le conflit', () => {
        const postit = element({ slots: '4', broadcastRank: '2', hasConflict: 'true' })
        renderPostitContent(context, postit)
        expect(postit.classList.contains('postit--rebroadcast')).toBe(true)
        postit.dataset.broadcastRank = '1'
        postit.dataset.hasConflict = 'false'
        renderPostitContent(context, postit)
        expect(postit.classList.contains('postit--first')).toBe(true)
        expect(postit.classList.contains('postit--rebroadcast')).toBe(false)
        expect(postit.classList.contains('postit--conflict')).toBe(false)
        expect(postit.querySelector('.postit__alert')).toBeNull()
    })
})
