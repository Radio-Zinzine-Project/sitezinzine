import { describe, expect, test, vi } from 'vitest'
import * as emissions from '../../../../assets/controllers/grid/emissions'
import { element, jsonResponse, mockNavigation } from '../../support/dom'

function context(data = {}) {
    const list = element()
    return {
        currentMode: 'regular', selectedPostit: element({ slotId: '12', startsAt: 'destination', originalStartsAt: '2026-10-06 14:00:00', ...data }),
        regularExtended: false, regularOtherCategory: false, hasRegularSearchTarget: true,
        regularSearchTarget: element({}, 'input'), slotSummaryTarget: element(), slotActionsTarget: element(),
        setEmissionsListHtml: html => { list.innerHTML = html }, getCurrentEmissionsListTarget: () => list,
        renderEmissions: vi.fn(), renderPostitContent: vi.fn(), buildSlotSummary: () => '<p>Résumé</p>',
        loadCandidatesForSelectedPostit: vi.fn().mockResolvedValue(), saveScrollTarget: vi.fn(), clearRegularSearch: vi.fn(),
    }
}

describe('Candidats et affectations', () => {
    test.each([['ab', false], [' été ', true]])('recherche %s : le serveur reçoit les mots de trois caractères minimum', async (search, hasQuery) => {
        const ctx = context(); ctx.regularSearchTarget.value = search; ctx.regularExtended = true
        fetch.mockResolvedValue(jsonResponse({ items: [] }))
        await emissions.loadCandidatesForSelectedPostit.call(ctx)
        const url = new URL(fetch.mock.calls[0][0], 'http://localhost')
        expect(url.searchParams.get('startsAt')).toBe('2026-10-06 14:00:00')
        expect(url.searchParams.get('extended')).toBe('1')
        expect(url.searchParams.has('q')).toBe(hasQuery)
        if (hasQuery) expect(url.searchParams.get('q')).toBe('été')
    })

    test.each([
        [{}, [], true],
        [{ broadcastRank: '2' }, [], false],
        [{ assignedEmissionTitle: 'A' }, [], false],
        [{}, [{ isAutoGenerated: true }], false],
    ])('la création de direct dépend de la première occurrence vide %j', async (data, items, showCreateLive) => {
        const ctx = context(data); fetch.mockResolvedValue(jsonResponse({ items }))
        await emissions.loadCandidatesForSelectedPostit.call(ctx)
        expect(ctx.renderEmissions).toHaveBeenCalledWith({ items }, { showCreateLive })
    })

    test('affecter une occurrence sans propagation met à jour la carte et sa catégorie', async () => {
        const navigation = mockNavigation(); const ctx = context()
        const card = element({ emissionId: '42' }); ctx.getCurrentEmissionsListTarget().append(card)
        fetch.mockResolvedValue(jsonResponse({ success: true, emissionTitle: 'Titre', emissionCategoryTitle: 'Nouvelle catégorie', emissionCategorySlug: 'ABC' }))
        await emissions.selectEmission.call(ctx, { currentTarget: card })
        expect(ctx.selectedPostit.dataset.assignedEmissionId).toBe('42')
        expect(ctx.selectedPostit.dataset.categoryTitle).toBe('Nouvelle catégorie')
        expect(ctx.selectedPostit.classList.contains('assigned')).toBe(true)
        expect(card.classList.contains('is-selected')).toBe(true)
        expect(navigation.reload).not.toHaveBeenCalled()
    })

    test.each([{ isCancelled: 'true' }, { isRescheduledOrigin: 'true' }])('une origine projetée exige une reconstruction serveur %j', async data => {
        const navigation = mockNavigation(); const ctx = context(data)
        fetch.mockResolvedValue(jsonResponse({ success: true, propagated: false }))
        await emissions.selectEmission.call(ctx, { currentTarget: element({ emissionId: '42' }) })
        expect(ctx.saveScrollTarget).toHaveBeenCalledWith('2026-10-06 14:00:00')
        expect(navigation.reload).toHaveBeenCalledOnce()
        expect(ctx.renderPostitContent).not.toHaveBeenCalled()
    })

    test('retirer une première diffusion prévient du retrait des rediffs et nettoie l’affectation', async () => {
        const ctx = context({ assignedEmissionTitle: 'A', assignedEmissionId: '42' })
        ctx.selectedPostit.classList.add('assigned'); window.confirm.mockReturnValue(true)
        fetch.mockResolvedValue(jsonResponse({ success: true, propagated: false }))
        await emissions.removeAssignment.call(ctx)
        expect(window.confirm).toHaveBeenCalledWith(expect.stringContaining('rediffusions liées'))
        expect(ctx.selectedPostit.classList.contains('assigned')).toBe(false)
        expect(ctx.selectedPostit.dataset.assignedEmissionId).toBe('')
        expect(ctx.slotActionsTarget.style.display).toBe('none')
    })

    test('un refus serveur ne transforme pas une sélection en affectation', async () => {
        const ctx = context(); fetch.mockResolvedValue(jsonResponse({ error: 'Refus', success: false }, false))
        await emissions.selectEmission.call(ctx, { currentTarget: element({ emissionId: '42' }) })
        expect(ctx.selectedPostit.classList.contains('assigned')).toBe(false)
        expect(window.alert).toHaveBeenCalledWith('Refus')
    })

    test('charger les candidats ponctuels filtre par catégorie et recherche puis rend la liste courte', async () => {
        const ctx = context()

        ctx.currentMode = 'special'

        ctx.specialCategorySelectTarget = document.createElement('select')

        const option = document.createElement('option')
        option.value = '7'
        option.textContent = 'Catégorie test'
        ctx.specialCategorySelectTarget.append(option)
        ctx.specialCategorySelectTarget.value = '7'

        ctx.hasSpecialSearchTarget = true
        ctx.specialSearchTarget = element({}, 'input')
        ctx.specialSearchTarget.value = '  musique  '
        ctx.specialShowAllBtnTarget = element()
        ctx.specialStatusTarget = element()
        ctx.renderSpecialEmissions = vi.fn()

        fetch.mockResolvedValue(
            jsonResponse({
                items: [
                    {
                        id: 42,
                        title: 'Émission musicale'
                    }
                ]
            })
        )

        await emissions.loadSpecialCandidates.call(ctx)

        const url = new URL(
            fetch.mock.calls[0][0],
            'http://localhost'
        )

        expect(url.pathname).toBe(
            '/admin/grille/special-candidates'
        )
        expect(url.searchParams.get('categoryId')).toBe('7')
        expect(url.searchParams.get('all')).toBe('0')
        expect(url.searchParams.get('q')).toBe('musique')

        expect(ctx.renderSpecialEmissions).toHaveBeenCalledWith(
            {
                items: [
                    {
                        id: 42,
                        title: 'Émission musicale'
                    }
                ]
            },
            false
        )
    })

    test('charger toutes les émissions ponctuelles demande la liste complète de la catégorie', async () => {
        const ctx = context()

        ctx.currentMode = 'special'

        ctx.specialCategorySelectTarget = document.createElement('select')

        const option = document.createElement('option')
        option.value = '7'
        option.textContent = 'Catégorie test'
        ctx.specialCategorySelectTarget.append(option)
        ctx.specialCategorySelectTarget.value = '7'

        ctx.hasSpecialSearchTarget = false
        ctx.specialShowAllBtnTarget = element()
        ctx.specialStatusTarget = element()
        ctx.renderSpecialEmissions = vi.fn()

        fetch.mockResolvedValue(
            jsonResponse({
                items: [
                    {
                        id: 42,
                        title: 'Émission A'
                    },
                    {
                        id: 43,
                        title: 'Émission B'
                    }
                ],
                total: 2
            })
        )

        await emissions.loadAllSpecialCandidates.call(ctx)

        const url = new URL(
            fetch.mock.calls[0][0],
            'http://localhost'
        )

        expect(url.pathname).toBe(
            '/admin/grille/special-candidates'
        )
        expect(url.searchParams.get('categoryId')).toBe('7')
        expect(url.searchParams.get('all')).toBe('1')
        expect(url.searchParams.has('q')).toBe(false)

        expect(ctx.renderSpecialEmissions).toHaveBeenCalledWith(
            {
                items: [
                    {
                        id: 42,
                        title: 'Émission A'
                    },
                    {
                        id: 43,
                        title: 'Émission B'
                    }
                ],
                total: 2
            },
            true
        )
    })

    test('le rendu ponctuel crée le direct, les émissions draggables et propose de charger la suite', () => {
        const ctx = context()

        ctx.specialCategorySelectTarget = document.createElement('select')

        const option = document.createElement('option')
        option.value = '7'
        option.textContent = 'Catégorie test'
        ctx.specialCategorySelectTarget.append(option)
        ctx.specialCategorySelectTarget.value = '7'

        ctx.specialShowAllBtnTarget = element()
        ctx.specialStatusTarget = element()
        ctx.makeDraggable = vi.fn()

        emissions.renderSpecialEmissions(
            ctx,
            {
                items: [
                    {
                        id: 42,
                        title: '<Émission test>',
                        durationMinutes: 45,
                        meta: '<Meta>',
                        playLabel: '1 diffusion'
                    }
                ],
                total: 12,
                hasMore: true
            },
            false
        )

        const list = ctx.getCurrentEmissionsListTarget()
        const cards = list.querySelectorAll('.emission-card')

        expect(cards).toHaveLength(2)

        expect(
            list.querySelector('[data-special-item-type="manual_live"]')
        ).not.toBeNull()

        const emissionCard = list.querySelector(
            '[data-special-item-type="manual_emission"]'
        )

        expect(emissionCard).not.toBeNull()
        expect(emissionCard.dataset.emissionId).toBe('42')
        expect(emissionCard.dataset.emissionDuration).toBe('45')

        expect(list.innerHTML).toContain('&lt;Émission test&gt;')
        expect(list.innerHTML).toContain('&lt;Meta&gt;')

        expect(ctx.makeDraggable).toHaveBeenCalledTimes(2)

        expect(ctx.specialShowAllBtnTarget.style.display).toBe(
            'block'
        )

        expect(ctx.specialStatusTarget.textContent).toContain(
            '12 émission(s) disponible(s)'
        )
    })

    test('créer un direct affecte immédiatement la nouvelle émission au créneau', async () => {
        const ctx = context()

        ctx.selectedPostit.dataset.startsAt =
            '2026-10-06 14:00:00'

        fetch.mockResolvedValue(
            jsonResponse({
                success: true,
                emissionId: 99,
                emissionTitle: 'Direct',
                propagated: false
            })
        )

        await emissions.createLiveEmission.call(ctx)

        expect(fetch.mock.calls[0][0]).toBe(
            '/admin/grille/create-live'
        )

        expect(
            Object.fromEntries(fetch.mock.calls[0][1].body)
        ).toEqual({
            slotId: '12',
            startsAt: '2026-10-06 14:00:00'
        })

        expect(ctx.selectedPostit.dataset.assignedEmissionId).toBe(
            '99'
        )

        expect(ctx.selectedPostit.dataset.assignedEmissionTitle).toBe(
            'Direct'
        )

        expect(ctx.selectedPostit.dataset.emissionIsAutoGenerated).toBe(
            'true'
        )

        expect(ctx.selectedPostit.classList.contains('assigned')).toBe(
            true
        )
    })

    test('une affectation propagée recharge la grille sans modifier localement le post-it', async () => {
        const navigation = mockNavigation()
        const ctx = context()

        ctx.selectedPostit.dataset.startsAt =
            '2026-10-06 14:00:00'

        const card = element({
            emissionId: '42'
        })

        fetch.mockResolvedValue(
            jsonResponse({
                success: true,
                emissionTitle: 'Émission propagée',
                propagated: true
            })
        )

        await emissions.selectEmission.call(ctx, {
            currentTarget: card
        })

        expect(ctx.saveScrollTarget).toHaveBeenCalledWith(
            '2026-10-06 14:00:00'
        )

        expect(navigation.reload).toHaveBeenCalledOnce()

        expect(ctx.renderPostitContent).not.toHaveBeenCalled()
        expect(card.classList.contains('is-selected')).toBe(false)
    })

    test('retirer une affectation propagée mémorise le créneau puis recharge toute la grille', async () => {
        const navigation = mockNavigation()

        const ctx = context({
            assignedEmissionTitle: 'Émission test',
            assignedEmissionId: '42',
            startsAt: '2026-10-06 14:00:00'
        })

        ctx.selectedPostit.classList.add('assigned')
        window.confirm.mockReturnValue(true)

        fetch.mockResolvedValue(
            jsonResponse({
                success: true,
                propagated: true
            })
        )

        await emissions.removeAssignment.call(ctx)

        expect(ctx.saveScrollTarget).toHaveBeenCalledWith(
            '2026-10-06 14:00:00'
        )

        expect(navigation.reload).toHaveBeenCalledOnce()

        expect(ctx.renderPostitContent).not.toHaveBeenCalled()
        expect(
            ctx.loadCandidatesForSelectedPostit
        ).not.toHaveBeenCalled()

        expect(
            ctx.selectedPostit.dataset.assignedEmissionId
        ).toBe('42')
    })
})
