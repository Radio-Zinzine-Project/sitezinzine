    test('échappe les données de diffusion dans les infobulles', () => {
        const ctx = context()

        emissions.renderEmissions(ctx, {
            items: [{
                id: 42,
                title: '<img src=x onerror=alert(1)>',
                durationMinutes: 60,
                diffusionHistory: {
                    total: 1,
                    remaining: 0,
                    items: [{
                        date: '<img src=x onerror=alert(1)>',
                        nombreDiffusion: 1,
                        assignmentGroupKey: '<img src=x onerror=alert(2)>'
                    }]
                }
            }]
        })

        const card = ctx.getCurrentEmissionsListTarget()
            .querySelector('.emission-card')

        const tooltip = card.querySelector('.emission-card__tooltip')

        expect(card.querySelector('img')).toBeNull()
        expect(tooltip.textContent).toContain(
            '<img src=x onerror=alert(1)>'
        )
        expect(tooltip.querySelector('img')).toBeNull()

        // La clé technique ne doit plus être visible.
        expect(tooltip.textContent).not.toContain(
            '<img src=x onerror=alert(2)>'
        )

        // Elle doit uniquement servir à identifier la couleur de la pastille.
        const marker = tooltip.querySelector('.emission-card__group-marker')

        expect(marker).not.toBeNull()
        expect(marker.dataset.groupColor).toBeTruthy()

        // Aucune donnée malveillante ne doit créer d'élément HTML.
        expect(tooltip.querySelector('img')).toBeNull()
    })

