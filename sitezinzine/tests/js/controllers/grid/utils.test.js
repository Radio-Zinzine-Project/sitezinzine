import { describe, expect, test, vi } from 'vitest'
import { escapeHtml, getSlotData, validateSlotData, updateAssignedPostit } from '../../../../assets/controllers/grid/utils'
import { element } from '../../support/dom'

describe('Identité et affectation d’une occurrence', () => {
    test('échappe les textes sans permettre de créer du HTML', () => {
        const container = element()
        const text = '<img src=x onerror="alert(1)"> & "titre" \'direct\''
        container.innerHTML = escapeHtml(text)
        expect(container.textContent).toBe(text)
        expect(container.querySelector('img')).toBeNull()
        expect(escapeHtml(null)).toBe('')
    })

    test('utilise l’origine pour identifier une occurrence déplacée', () => {
        expect(getSlotData(element({ slotId: '12', startsAt: 'destination', originalStartsAt: 'origine' })))
            .toEqual({ slotId: '12', startsAt: 'origine' })
        expect(getSlotData(element({ slotId: '12', startsAt: 'date' })))
            .toEqual({ slotId: '12', startsAt: 'date' })
    })

    test('une identité incomplète interrompt l’action avec un message', () => {
        expect(validateSlotData('', 'date', 'Créneau manquant')).toBe(false)
        expect(window.alert).toHaveBeenCalledWith('Créneau manquant')
        expect(validateSlotData('12', 'date')).toBe(true)
    })

    test('l’affectation met à jour la carte, la sidebar et les candidats', async () => {
        const context = {
            selectedPostit: element(), slotSummaryTarget: element(), slotActionsTarget: element(),
            renderPostitContent: vi.fn(), buildSlotSummary: vi.fn(() => '<p>Émission</p>'),
            loadCandidatesForSelectedPostit: vi.fn().mockResolvedValue(),
        }
        await updateAssignedPostit(context, 42, 'Le direct', true)
        expect(context.selectedPostit.dataset.assignedEmissionId).toBe('42')
        expect(context.selectedPostit.dataset.emissionIsAutoGenerated).toBe('true')
        expect(context.selectedPostit.classList.contains('assigned')).toBe(true)
        expect(context.slotSummaryTarget.textContent).toBe('Émission')
        expect(context.slotActionsTarget.style.display).toBe('block')
        expect(context.loadCandidatesForSelectedPostit).toHaveBeenCalledOnce()
    })
})
