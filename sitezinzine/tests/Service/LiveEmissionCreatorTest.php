    public function testCreateFromSlotCreatesEmission(): void
    {
        $startsAt = new \DateTimeImmutable('2026-09-15 14:30:00');

        $category = $this->createCategory(
            id: 42,
            title: 'Musique',
            duration: 60,
        );

        $rule = new ProgrammationRule();
        $rule->setCategory($category);

        $slot = new ProgrammationRuleSlot();
        $slot->setRule($rule);
        $slot->setDurationMinutes(45);

        $theme = new Theme();

        $this->connection
            ->expects($this->once())
            ->method('fetchAllAssociative')
            ->with(
                'SELECT user_id FROM categories_user WHERE categories_id = :categoryId',
                ['categoryId' => 42]
            )
            ->willReturn([]);

        $this->themeRepository
            ->expects($this->once())
            ->method('find')
            ->with(15)
            ->willReturn($theme);

        $this->entityManager
            ->expects($this->once())
            ->method('persist')
            ->with($this->isInstanceOf(Emission::class));

        $this->entityManager
            ->expects($this->once())
            ->method('flush');

        $emission = $this->service->createFromSlot($slot, $startsAt);

        $this->assertSame(
            'Direct du 15/09/2026 - Musique',
            $emission->getTitre()
        );

        $this->assertSame('', $emission->getKeyword());
        $this->assertSame('', $emission->getRef());
        $this->assertSame(45, $emission->getDuree());
        $this->assertNull($emission->getUrl());
        $this->assertSame($category, $emission->getCategorie());
        $this->assertSame($theme, $emission->getTheme());

        $this->assertSame(
            '15/09/2026 14:30',
            $emission->getDatepub()?->format('d/m/Y H:i')
        );

        $this->assertSame(
            '15/09/2026 14:30',
            $emission->getAutoGeneratedForStartsAt()?->format('d/m/Y H:i')
        );

        $this->assertSame(
            $slot,
            $emission->getAutoGeneratedForSlot()
        );

        $this->assertStringContainsString(
            'générée automatiquement depuis la grille de programmation',
            $emission->getDescriptif()
        );

        $this->assertStringContainsString(
            'catégorie « Musique »',
            $emission->getDescriptif()
        );
    }

