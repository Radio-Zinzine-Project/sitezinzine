    public function testCreateFromSlotAddsCategoryUsersWithoutDuplicates(): void
    {
        $startsAt = new \DateTimeImmutable('2026-09-15 16:00:00');

        $category = $this->createCategory(
            id: 25,
            title: 'Culture',
        );

        $rule = new ProgrammationRule();
        $rule->setCategory($category);

        $slot = new ProgrammationRuleSlot();
        $slot->setRule($rule);
        $slot->setDurationMinutes(30);

        $theme = new Theme();

        $user1 = new User();
        $user1
            ->setUsername('user1')
            ->setEmail('user1@example.com')
            ->setPassword('fake');

        $user2 = new User();
        $user2
            ->setUsername('user2')
            ->setEmail('user2@example.com')
            ->setPassword('fake');

        $this->connection
            ->expects($this->once())
            ->method('fetchAllAssociative')
            ->willReturn([
                ['user_id' => 3],
                ['user_id' => 7],
                ['user_id' => 3],
                [],
            ]);

        $this->userRepository
            ->expects($this->once())
            ->method('findBy')
            ->with(['id' => [3, 7]])
            ->willReturn([$user1, $user2]);

        $this->themeRepository
            ->method('find')
            ->with(15)
            ->willReturn($theme);

        $this->entityManager
            ->expects($this->once())
            ->method('persist');

        $this->entityManager
            ->expects($this->once())
            ->method('flush');

        $emission = $this->service->createFromSlot($slot, $startsAt);

        $this->assertCount(2, $emission->getUsers());
        $this->assertTrue($emission->getUsers()->contains($user1));
        $this->assertTrue($emission->getUsers()->contains($user2));
    }

