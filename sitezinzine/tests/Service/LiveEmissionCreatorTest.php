    private function createCategory(
        int $id,
        string $title,
        ?int $duration = 60,
        bool $active = true,
        bool $softDelete = false,
        ?Editeur $editeur = null,
    ): Categories {
        $category = new Categories();

        $reflection = new \ReflectionProperty(
            Categories::class,
            'id'
        );

        $reflection->setAccessible(true);
        $reflection->setValue($category, $id);

        $category->setTitre($title);

        if ($duration !== null) {
            $category->setDuree($duration);
        }

        $category->setActive($active);
        $category->setSoftDelete($softDelete);
        $category->setEditeur($editeur);

        return $category;
    }
