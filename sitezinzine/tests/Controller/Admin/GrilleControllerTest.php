    /** @dataProvider publicationActions */
    public function testPublicationActionsReportCountsAndRedirectToNormalizedWeek(string $action): void
    {
        $drafts = $this->createMock(DiffusionDraftRepository::class);
        $diffusions = $this->createMock(DiffusionRepository::class);
        $arbitrations = $this->createMock(GridSlotArbitrationRepository::class);

        $arbitrations
            ->method('findRelevantForWeek')
            ->willReturn([]);

        $em = $this->createMock(EntityManagerInterface::class);
        $em->expects(self::once())
            ->method('wrapInTransaction')
            ->willReturnCallback(static fn(callable $work) => $work());

        $em->expects(
            self::exactly('publish' === $action ? 2 : 1)
        )->method('flush');

        $existing = new \App\Entity\Diffusion();
        (new \ReflectionProperty($existing, 'id'))->setValue($existing, 101);

        $existing
            ->setEmission($this->createEmission())
            ->setNombreDiffusion(1)
            ->setSchedule(new \DateTime('2026-09-15 10:00:00'), 30);

        $linked = $this->publicationDraft('2026-09-15 10:00:00');
        $linked->markAsPublished($existing, new \DateTimeImmutable());

        if ('publish' === $action) {
            $new = $this->publicationDraft('2026-09-15 11:00:00');

            $drafts
                ->method('findPublishableByWeek')
                ->willReturn([$linked, $new]);

            $diffusions
                ->method('findByWeek')
                ->willReturn([$existing]);

