    public function testCandidatesReturnsRegularCandidatesAndFiltersAlreadyDiffusedEmissions(): void
    {
        $category = $this->createCategory(
            id: 20,
            title: 'Catégorie régulière'
        );

        $rule = $this->createRule();

        $rule
            ->method('getCategory')
            ->willReturn($category);

        $slot = $this->createValidSlot(
            broadcastRank: 1,
            rule: $rule
        );

        $availableEmission = $this->createMock(Emission::class);
        $availableEmission->method('getId')->willReturn(31);
        $availableEmission->method('getTitre')->willReturn('Émission disponible');
        $availableEmission->method('getDatepub')->willReturn(
            new \DateTimeImmutable('2026-09-10')
        );
        $availableEmission->method('getDuree')->willReturn(45);
        $availableEmission->method('getCategorie')->willReturn($category);
        $availableEmission->method('isAutoGenerated')->willReturn(false);
        $availableEmission->method('getDiffusions')->willReturn(
            new ArrayCollection()
        );

        $alreadyDiffusedEmission = $this->createMock(Emission::class);
        $alreadyDiffusedEmission->method('getId')->willReturn(32);
        $alreadyDiffusedEmission->method('getDiffusions')->willReturn(
            new ArrayCollection([new \stdClass()])
        );

        $autoGeneratedEmission = $this->createMock(Emission::class);
        $autoGeneratedEmission->method('getId')->willReturn(33);
        $autoGeneratedEmission->method('getTitre')->willReturn('Direct automatique');
        $autoGeneratedEmission->method('getDatepub')->willReturn(null);
        $autoGeneratedEmission->method('getDuree')->willReturn(60);
        $autoGeneratedEmission->method('getCategorie')->willReturn($category);
        $autoGeneratedEmission->method('isAutoGenerated')->willReturn(true);

        $slotRepository = $this->createMock(
            ProgrammationRuleSlotRepository::class
        );

        $slotRepository
            ->method('find')
            ->willReturn($slot);

        $emissionRepository = $this->createMock(
            EmissionRepository::class
        );

        $emissionRepository
            ->expects(self::once())
            ->method('findGridCandidatesByCategory')
            ->with(
                $category,
                null,
                false,
                20
            )
            ->willReturn([
                $availableEmission,
                $alreadyDiffusedEmission,
            ]);

        $emissionRepository
            ->expects(self::once())
            ->method('findAutoGeneratedForSlotAndStartsAt')
            ->with(
                $slot,
                self::isInstanceOf(\DateTimeImmutable::class)
            )
            ->willReturn($autoGeneratedEmission);

        // Historique publié de l'émission disponible.
        $publishedDiffusion = $this->createMock(Diffusion::class);

        $publishedDiffusion
            ->method('getHoraireDiffusion')
            ->willReturn(new \DateTime('2026-10-20 14:00:00'));

        $publishedDiffusion
            ->method('getNombreDiffusion')
            ->willReturn(3);

        $publishedDiffusion
            ->method('getAssignmentGroupKey')
            ->willReturn('manual_100');

        // Ancienne diffusion sans groupe d'affectation.
        $historicalDiffusion = $this->createMock(Diffusion::class);

        $historicalDiffusion
            ->method('getHoraireDiffusion')
            ->willReturn(new \DateTime('2026-10-18 10:00:00'));

        $historicalDiffusion
            ->method('getNombreDiffusion')
            ->willReturn(1);

        $historicalDiffusion
            ->method('getAssignmentGroupKey')
            ->willReturn(null);

        $diffusionRepository = $this->createMock(
            DiffusionRepository::class
        );

        // Une seule récupération groupée pour les émissions affichées.
        // L'émission 32, filtrée, ne doit pas être interrogée.
        $diffusionRepository
            ->expects(self::once())
            ->method('findPublishedHistoryForEmissionIds')
            ->with([33, 31], 6)
            ->willReturn([
                33 => [
                    'total' => 0,
                    'items' => [],
                ],
                31 => [
                    'total' => 2,
                    'items' => [
                        $publishedDiffusion,
                        $historicalDiffusion,
                    ],
                ],
            ]);

        $request = Request::create(
            '/admin/grille/candidates',
            'GET',
            [
                'slotId' => 123,
                'startsAt' => '2026-09-15 10:00:00',
            ]
        );

        $response = $this->controller->candidates(
            $request,
            $slotRepository,
            $emissionRepository,
            $this->createMock(CategoriesRepository::class),
            $diffusionRepository
        );

        self::assertSame(200, $response->getStatusCode());

        $data = $this->json($response);

        // Vérification du contrat JSON existant.
        self::assertFalse($data['extended']);
        self::assertSame('', $data['search']);
        self::assertSame(20, $data['categoryId']);
        self::assertSame('Catégorie régulière', $data['categoryTitle']);
        self::assertFalse($data['isOverrideCategory']);
        self::assertCount(2, $data['items']);

        // L'émission auto-générée reste en première position.
        self::assertSame(33, $data['items'][0]['id']);
        self::assertSame('Direct automatique', $data['items'][0]['title']);
        self::assertSame(
            'date inconnue • 60 min • Catégorie régulière',
            $data['items'][0]['meta']
        );
        self::assertTrue($data['items'][0]['isAutoGenerated']);

        // L'émission disponible reste en seconde position.
        self::assertSame(31, $data['items'][1]['id']);
        self::assertSame('Émission disponible', $data['items'][1]['title']);
        self::assertSame(
            '10/09/2026 • 45 min • Catégorie régulière',
            $data['items'][1]['meta']
        );
        self::assertSame(45, $data['items'][1]['durationMinutes']);
        self::assertFalse($data['items'][1]['isAutoGenerated']);

        // L'émission auto-générée possède un historique vide.
        self::assertSame(
            [
                'total' => 0,
                'items' => [],
                'remaining' => 0,
            ],
            $data['items'][0]['diffusionHistory']
        );

        // L'émission disponible possède son historique publié.
        $history = $data['items'][1]['diffusionHistory'];

        self::assertSame(2, $history['total']);
        self::assertSame(0, $history['remaining']);
        self::assertCount(2, $history['items']);

        // Diffusion récente avec groupe.
        self::assertSame(
            '2026-10-20 14:00:00',
            $history['items'][0]['date']
        );
        self::assertSame(
            3,
            $history['items'][0]['nombreDiffusion']
        );
        self::assertSame(
            'manual_100',
            $history['items'][0]['assignmentGroupKey']
        );

        // Diffusion historique sans groupe.
        self::assertSame(
            '2026-10-18 10:00:00',
            $history['items'][1]['date']
        );
        self::assertSame(
            1,
            $history['items'][1]['nombreDiffusion']
        );
        self::assertNull(
            $history['items'][1]['assignmentGroupKey']
        );
    }

