import { escapeHtml } from './utils'

export function getStatusLabel(postit) {
    const isCancelled = postit.dataset.isCancelled === 'true'
    const isRescheduledOrigin = postit.dataset.isRescheduledOrigin === 'true'
    const isLive = postit.dataset.emissionIsAutoGenerated === 'true'
    const isProjectedOverride = postit.dataset.isProjectedOverride === 'true'
    const isManualDraft = postit.dataset.isManualDraft === 'true'
    const broadcastRank = parseInt(postit.dataset.broadcastRank || '1', 10)

    if (isCancelled) {
        return 'Créneau annulé'
    }

    if (isRescheduledOrigin) {
        return 'Ancien emplacement déplacé'
    }

    if (isManualDraft) {
        return isLive ? 'Direct ponctuel' : 'Programmation ponctuelle'
    }

    if (broadcastRank > 1) {
        return `Rediffusion ${broadcastRank - 1}`
    }

    if (isProjectedOverride) {
        return 'Occurrence déplacée'
    }

    if (isLive) {
        return 'Direct'
    }

    return '1re diffusion'
}

export function buildSlotSummary(context, postit, assignedEmissionTitle = '') {
    const isManualDraft = postit.dataset.isManualDraft === 'true'
    const categoryTitle = postit.dataset.categoryTitle || 'Catégorie inconnue'
    const ruleDisplayName = postit.dataset.ruleDisplayName || categoryTitle
    const startsAt = postit.dataset.startsAt || ''
    const endsAt = postit.dataset.endsAt || ''
    const draftId = postit.dataset.draftId || ''

    const safeAssignedTitle =
        assignedEmissionTitle ||
        postit.dataset.assignedEmissionTitle ||
        ''

    const statusLabel = context.getStatusLabel(postit)

    if (isManualDraft) {
        return `
            <div><span class="label">Type :</span> ${escapeHtml(statusLabel)}</div>
            <div><span class="label">Catégorie :</span> ${escapeHtml(categoryTitle)}</div>
            <div><span class="label">Début :</span> ${escapeHtml(formatSidebarDate(startsAt))}</div>
            ${endsAt ? `<div><span class="label">Fin :</span> ${escapeHtml(formatSidebarDate(endsAt))}</div>` : ''}
            ${safeAssignedTitle
                ? `<div><span class="label">Émission :</span> ${escapeHtml(safeAssignedTitle)}</div>`
                : ''
            }
        `
    }

    return `
        <div><span class="label">Règle :</span> ${escapeHtml(ruleDisplayName)}</div>
        <div><span class="label">Catégorie :</span> ${escapeHtml(categoryTitle)}</div>
        <div><span class="label">Début :</span> ${escapeHtml(formatSidebarDate(startsAt))}</div>
        ${endsAt ? `<div><span class="label">Fin :</span> ${escapeHtml(formatSidebarDate(endsAt))}</div>` : ''}
        <div><span class="label">Type :</span> ${escapeHtml(statusLabel)}</div>
        ${safeAssignedTitle
            ? `<div><span class="label">Émission affectée :</span> ${escapeHtml(safeAssignedTitle)}</div>`
            : ''
        }
        ${context.buildProjectionSummary(postit)}
        ${context.buildConflictSummary(postit)}
        ${safeAssignedTitle && draftId
            ? `
                    <div
                        class="linked-diffusions"
                        data-linked-diffusions-for="${escapeHtml(draftId)}"
                    >
                        Chargement des diffusions liées…
                    </div>
                `
            : ''
        }
    `
}


export function buildSpecialSlotSummary(context, postit) {
    const startsAt = postit.dataset.startsAt || ''
    const endsAt = postit.dataset.endsAt || ''
    const categoryTitle = postit.dataset.categoryTitle || 'Créneau manuel'
    const title = postit.dataset.assignedEmissionTitle || ''
    const isLive = postit.dataset.emissionIsAutoGenerated === 'true'
    const isManualDraft = postit.dataset.isManualDraft === 'true'
    const draftType = postit.dataset.draftType || ''
    const draftId = postit.dataset.draftId || ''
    const nombreDiffusion = parseInt(postit.dataset.nombreDiffusion || '1', 10)

    const typeLabel =
        draftType === 'manual_rebroadcast'
            ? `Rediffusion non régulière ${nombreDiffusion - 1}`
            : (isLive ? 'Direct non régulier' : 'Non régulière')

    let html = `
        <div><span class="label">Début :</span> ${context.escapeHtml(formatSidebarDate(startsAt))}</div>
        ${endsAt ? `<div><span class="label">Fin :</span> ${context.escapeHtml(formatSidebarDate(endsAt))}</div>` : ''}
        <div><span class="label">Catégorie :</span> ${context.escapeHtml(categoryTitle)}</div>
        ${title ? `<div><span class="label">Émission :</span> ${context.escapeHtml(title)}</div>` : ''}
        <div><span class="label">Type :</span> ${context.escapeHtml(typeLabel)}</div>
    `

    if (draftId) {
        html += `
            <div
                class="linked-diffusions"
                data-linked-diffusions-for="${context.escapeHtml(draftId)}"
            >
                Chargement des diffusions liées…
            </div>
        `
    }

    if (isManualDraft && draftType !== 'manual_rebroadcast') {
        html += `
            <div class="slot-actions">
                <button
                    type="button"
                    class="btn-arbitration"
                    data-action="click->grid#openRebroadcastModal"
                >
                    Ajouter des rediffs ponctuelles
                </button>
            </div>
        `
    }

    return html
}


export async function selectSlot(context, event) {
    const postit = event.currentTarget
    const isLocked = postit.dataset.slotLocked === 'true'
    const isManualDraft = postit.dataset.isManualDraft === 'true'
    const isGhost =
        postit.dataset.canRestore === 'true' ||
        postit.dataset.isBlocking === 'false'

    if (context.selectedPostit) {
        context.selectedPostit.classList.remove('is-selected')
    }

    context.selectedPostit = postit
    context.selectedPostit.classList.add('is-selected')

    if (context.currentMode === 'special' || isManualDraft) {
        context.specialEmptyStateTarget.style.display = 'none'
        context.specialSidebarPanelTarget.style.display = 'block'

        context.specialSlotSummaryTarget.innerHTML =
            context.buildSpecialSlotSummary(postit)

        await context.loadLinkedDiffusions()

        if (context.isReadonly()) {
            return
        }

        return
    }

    const assignedEmissionTitle =
        postit.dataset.assignedEmissionTitle || ''

    const hasConflict =
        postit.dataset.hasConflict === 'true'

    context.emptyStateTarget.style.display = 'none'
    context.sidebarPanelTarget.style.display = 'block'

    context.slotSummaryTarget.innerHTML =
        context.buildSlotSummary(
            postit,
            assignedEmissionTitle
        )

    await context.loadLinkedDiffusions()

    if (context.isReadonly()) {
        context.arbitrationActionsTarget.innerHTML = ''
        context.arbitrationActionsTarget.style.display = 'none'
        context.slotActionsTarget.style.display = 'none'

        context.setEmissionsListHtml(
            '<div>Cette semaine est validée. Le créneau est affiché en lecture seule.</div>'
        )

        return
    }

    if (hasConflict && !isGhost) {
        context.arbitrationActionsTarget.innerHTML =
            context.buildConflictArbitrationUI(postit)
    } else {
        context.arbitrationActionsTarget.innerHTML =
            context.buildArbitrationActions(postit)
    }

    context.arbitrationActionsTarget.style.display =
        context.arbitrationActionsTarget.innerHTML.trim()
            ? 'flex'
            : 'none'

    context.slotActionsTarget.style.display =
        !isLocked && !isGhost && assignedEmissionTitle
            ? 'block'
            : 'none'

    if (isGhost) {
        context.setEmissionsListHtml(
            '<div>Ce créneau est annulé ou déplacé. Il ne bloque pas la grille et peut être restauré.</div>'
        )
        return
    }

    if (isLocked) {
        context.setEmissionsListHtml(
            '<div>Ce créneau est verrouillé pour l’affectation, mais peut être ajusté via l’arbitrage.</div>'
        )
        return
    }

    context.clearRegularSearch()
    await context.loadCandidatesForSelectedPostit()
}

export async function loadLinkedDiffusions() {
    if (!this.selectedPostit) {
        return
    }

    const draftId = this.selectedPostit.dataset.draftId || ''

    if (!draftId) {
        return
    }

    const root =
        this.currentMode === 'special' ||
            this.selectedPostit.dataset.isManualDraft === 'true'
            ? this.specialSlotSummaryTarget
            : this.slotSummaryTarget

    const container =
        root.querySelector('[data-linked-diffusions-for]')

    if (!container) {
        return
    }

    try {
        const response = await fetch(
            `/admin/grid-drafts/${draftId}/group`
        )

        const data = await response.json()

        const items = Array.isArray(data.items)
            ? data.items
            : []

        if (!items.length) {
            container.innerHTML = ''
            return
        }

        container.innerHTML = `
            <div
                style="
                    margin-top:12px;
                    padding-top:12px;
                    border-top:1px solid #ddd;
                "
            >
                <strong>Diffusions du groupe</strong>

                ${items.map((item) => `
                    <div style="margin-top:6px;">
                        <strong>${escapeHtml(item.label)}</strong><br>
                        <small>
                            ${escapeHtml(formatSidebarDate(item.startsAt))}
                        </small>
                    </div>
                `).join('')}
            </div>
        `
    } catch {
        container.innerHTML =
            '<div>Impossible de charger les diffusions liées.</div>'
    }
}

export function formatSidebarDate(value) {
    if (!value) {
        return ''
    }

    const date = new Date(
        value.replace(' ', 'T')
    )

    if (Number.isNaN(date.getTime())) {
        return value
            .replace(':00', '')
            .replace(/:\d\d$/, '')
    }

    return date.toLocaleString(
        'fr-FR',
        {
            weekday: 'short',
            day: '2-digit',
            month: '2-digit',
            hour: '2-digit',
            minute: '2-digit'
        }
    )
}