import { escapeHtml } from './utils'

export function getStatusLabel(postit) {
    const isCancelled = postit.dataset.isCancelled === 'true'
    const isRescheduledOrigin = postit.dataset.isRescheduledOrigin === 'true'
    const isLive = postit.dataset.emissionIsAutoGenerated === 'true'
    const isProjectedOverride = postit.dataset.isProjectedOverride === 'true'
    const isManualDraft = postit.dataset.isManualDraft === 'true'
    const broadcastRank = parseInt(postit.dataset.broadcastRank || '1', 10)

    if (isCancelled) {
        return 'Créneau annulé'
    }

    if (isRescheduledOrigin) {
        return 'Ancien emplacement déplacé'
    }

    if (isManualDraft) {
        return isLive ? 'Direct ponctuel' : 'Programmation ponctuelle'
    }

    if (broadcastRank > 1) {
        return `Rediffusion ${broadcastRank - 1}`
    }

    if (isProjectedOverride) {
        return 'Occurrence déplacée'
    }

    if (isLive) {
        return 'Direct'
    }

    return '1re diffusion'
}

export function buildSlotSummary(context, postit, emissionTitle = null) {
    const title =
        emissionTitle ||
        postit.dataset.assignedEmissionTitle ||
        postit.dataset.categoryTitle ||
        'Créneau'

    const startsAt = postit.dataset.startsAt || ''
    const endsAt = postit.dataset.endsAt || ''
    const status = context.getStatusLabel(postit)

    let html = `
    <div class="slot-summary">

      <div class="slot-summary__title">
        ${escapeHtml(title)}
      </div>

      <div class="slot-summary__row">
        <span class="label">Début :</span>
        ${escapeHtml(startsAt)}
      </div>

      ${endsAt
            ? `
          <div class="slot-summary__row">
            <span class="label">Fin :</span>
            ${escapeHtml(endsAt)}
          </div>
        `
            : ''
        }

      <div class="slot-summary__row">
        <span class="label">Type :</span>
        ${escapeHtml(status)}
      </div>
  `

    if (postit.dataset.hasConflict === 'true') {
        html += context.buildConflictSummary(postit)
    }

    html += '</div>'

    return html
}

export async function selectSlot(context, event) {
    const postit = event.currentTarget
    const isLocked = postit.dataset.slotLocked === 'true'
    const isManualDraft = postit.dataset.isManualDraft === 'true'
    const isGhost =
        postit.dataset.canRestore === 'true' ||
        postit.dataset.isBlocking === 'false'

    if (context.selectedPostit) {
        context.selectedPostit.classList.remove('is-selected')
    }

    context.selectedPostit = postit
    context.selectedPostit.classList.add('is-selected')

    if (context.currentMode === 'special' || isManualDraft) {
        context.specialEmptyStateTarget.style.display = 'none'
        context.specialSidebarPanelTarget.style.display = 'block'
        context.specialSlotSummaryTarget.innerHTML =
            context.buildSpecialSlotSummary(postit)

        return
    }

    const assignedEmissionTitle =
        postit.dataset.assignedEmissionTitle || ''

    const hasConflict =
        postit.dataset.hasConflict === 'true'

    context.emptyStateTarget.style.display = 'none'
    context.sidebarPanelTarget.style.display = 'block'
    context.slotSummaryTarget.innerHTML =
        context.buildSlotSummary(
            postit,
            assignedEmissionTitle
        )

    if (hasConflict && !isGhost) {
        context.arbitrationActionsTarget.innerHTML =
            context.buildConflictArbitrationUI(postit)
    } else {
        context.arbitrationActionsTarget.innerHTML =
            context.buildArbitrationActions(postit)
    }

    context.arbitrationActionsTarget.style.display =
        context.arbitrationActionsTarget.innerHTML.trim()
            ? 'flex'
            : 'none'

    context.slotActionsTarget.style.display =
        !isLocked && !isGhost && assignedEmissionTitle
            ? 'block'
            : 'none'

    if (isGhost) {
        context.setEmissionsListHtml(
            '<div>Ce créneau est annulé ou déplacé. Il ne bloque pas la grille et peut être restauré.</div>'
        )
        return
    }

    if (isLocked) {
        context.setEmissionsListHtml(
            '<div>Ce créneau est verrouillé pour l’affectation, mais peut être ajusté via l’arbitrage.</div>'
        )
        return
    }

    await context.loadCandidatesForSelectedPostit()
}