import { escapeHtml } from './utils'

export function getBadgeText(postit) {
    const isLive = postit.dataset.emissionIsAutoGenerated === 'true'
    const isProjectedOverride = postit.dataset.isProjectedOverride === 'true'
    const isManualDraft = postit.dataset.isManualDraft === 'true'
    const broadcastRank = parseInt(postit.dataset.broadcastRank || '1', 10)

    if (isManualDraft) {
        return isLive ? '● Direct' : ''
    }

    if (broadcastRank > 1) {
        return `↺ Rediff ${broadcastRank - 1}`
    }

    if (isProjectedOverride) {
        return '↔ Déplacé'
    }

    if (isLive) {
        return '● Direct'
    }

    return '■ 1re diff'
}

export function renderPostitContent(context, postit, title = null) {
    const displayTitle =
        title ||
        postit.dataset.assignedEmissionTitle ||
        postit.dataset.categoryTitle ||
        'Créneau'

    const badge = getBadgeText(postit)

    let badgeHtml = ''

    if (badge) {
        badgeHtml = `
      <span class="postit__badge">
        ${escapeHtml(badge)}
      </span>
    `
    }

    postit.innerHTML = `
    <div class="postit__content">

      <span class="postit__label">
        ${escapeHtml(displayTitle)}
      </span>

      ${badgeHtml}

    </div>
  `
}