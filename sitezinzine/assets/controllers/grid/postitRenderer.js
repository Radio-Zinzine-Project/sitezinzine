import { escapeHtml } from './utils'

export function applyPostitVariant(postit) {
    const isLive = postit.dataset.emissionIsAutoGenerated === 'true'
    const isProjectedOverride = postit.dataset.isProjectedOverride === 'true'
    const isManualDraft = postit.dataset.isManualDraft === 'true'
    const broadcastRank = parseInt(postit.dataset.broadcastRank || '1', 10)

    postit.classList.remove(
        'postit--first',
        'postit--live',
        'postit--rebroadcast',
        'postit--override',
        'postit--rescheduled'
    )

    if (isManualDraft) {
        postit.classList.add(isLive ? 'postit--live' : 'postit--override')
        return
    }

    if (broadcastRank > 1) {
        postit.classList.add('postit--rebroadcast')
        return
    }

    if (isProjectedOverride) {
        postit.classList.add('postit--rescheduled')
        return
    }

    if (isLive) {
        postit.classList.add('postit--live')
        return
    }

    postit.classList.add('postit--first')
}

export function applyConflictState(postit) {
    const hasConflict = postit.dataset.hasConflict === 'true'
    postit.classList.toggle('postit--conflict', hasConflict)

    if (hasConflict) {
        const severity = postit.dataset.conflictSeverity || ''

        if (severity) {
            postit.dataset.conflictSeverity = severity
        }
    }
}

export function getPostitLabels(postit, title = '') {
    const slots = parseInt(postit.dataset.slots || '1', 10)
    const categoryTitle = postit.dataset.categoryTitle || 'Catégorie inconnue'
    const categorySlug = postit.dataset.categorySlug || ''
    const safeTitle = title || postit.dataset.assignedEmissionTitle || ''

    if (safeTitle) {
        const displayCategory = categorySlug || categoryTitle

        if (slots < 4) {
            return {
                mainLabel: `${displayCategory} — ${safeTitle}`,
                secondaryLabel: ''
            }
        }

        return {
            mainLabel: displayCategory,
            secondaryLabel: safeTitle
        }
    }

    return {
        mainLabel: categoryTitle,
        secondaryLabel: ''
    }
}

export function getBadgeText(postit) {
    const isLive = postit.dataset.emissionIsAutoGenerated === 'true'
    const isProjectedOverride = postit.dataset.isProjectedOverride === 'true'
    const isManualDraft = postit.dataset.isManualDraft === 'true'
    const broadcastRank = parseInt(postit.dataset.broadcastRank || '1', 10)

    if (isManualDraft) {
        return isLive ? '● Direct' : ''
    }

    if (broadcastRank > 1) {
        return `↺ Rediff ${broadcastRank - 1}`
    }

    if (isProjectedOverride) {
        return '↔ Déplacé'
    }

    if (isLive) {
        return '● Direct'
    }

    return '■ 1re diff'
}

export function updatePostitTooltip(context, postit, assignedTitle = '') {
    const categoryTitle = postit.dataset.categoryTitle || 'Catégorie inconnue'
    const emissionTitle = assignedTitle || postit.dataset.assignedEmissionTitle || ''
    const statusLabel = context.getStatusLabel(postit)
    const hasConflict = postit.dataset.hasConflict === 'true'
    const conflictCount = parseInt(postit.dataset.conflictCount || '0', 10)

    let title = categoryTitle

    if (emissionTitle) {
        title += ` | ${emissionTitle}`
    }

    title += ` | ${statusLabel}`

    if (hasConflict) {
        title += ` | ⚠ ${context.getConflictSeverityLabel(postit)}`

        if (conflictCount > 0) {
            title += ` (${conflictCount})`
        }
    }

    postit.setAttribute('title', title)
}

export function renderPostitContent(context, postit, title = '') {
    applyPostitVariant(postit)
    applyConflictState(postit)

    const slots = parseInt(postit.dataset.slots || '1', 10)
    const badge = getBadgeText(postit)
    const { mainLabel, secondaryLabel } = getPostitLabels(postit, title)
    const hasConflict = postit.dataset.hasConflict === 'true'

    postit.innerHTML = `
        <div class="postit__content">
            <span class="postit__label">
                ${escapeHtml(mainLabel)}
            </span>

            ${secondaryLabel
            ? `<span class="postit__subline">${escapeHtml(secondaryLabel)}</span>`
            : ''
        }

            ${slots > 2 && hasConflict
            ? '<span class="postit__alert">⚠ Conflit</span>'
            : ''
        }

            ${slots > 2 && badge
            ? `<span class="postit__badge">${escapeHtml(badge)}</span>`
            : ''
        }
        </div>
    `

    updatePostitTooltip(context, postit, title)
}