export function escapeHtml(value) {
    return String(value ?? '')
        .replaceAll('&', '&amp;')
        .replaceAll('<', '&lt;')
        .replaceAll('>', '&gt;')
        .replaceAll('"', '&quot;')
        .replaceAll("'", '&#039;')
}

export function getSlotData(postit) {
    return {
        slotId: postit?.dataset.slotId || '',

        startsAt:
            postit?.dataset.originalStartsAt ||
            postit?.dataset.startsAt ||
            ''
    }
}

export function validateSlotData(
    slotId,
    startsAt,
    message = 'Informations incomplètes.'
) {
    if (!slotId || !startsAt) {
        alert(message)
        return false
    }

    return true
}

export async function updateAssignedPostit(
    context,
    emissionId,
    emissionTitle,
    autoGenerated = false
) {
    if (!context.selectedPostit) {
        return
    }

    context.selectedPostit.dataset.emissionIsAutoGenerated =
        autoGenerated ? 'true' : 'false'

    context.selectedPostit.dataset.assignedEmissionId = emissionId
    context.selectedPostit.dataset.assignedEmissionTitle = emissionTitle
    context.selectedPostit.classList.add('assigned')

    context.renderPostitContent(
        context.selectedPostit,
        emissionTitle
    )

    context.slotSummaryTarget.innerHTML =
        context.buildSlotSummary(
            context.selectedPostit,
            emissionTitle
        )

    context.slotActionsTarget.style.display = 'block'

    await context.loadCandidatesForSelectedPostit()
}