import { getJson, postForm } from './api'
import {
    escapeHtml,
    getSlotData,
    updateAssignedPostit
} from './utils'

export async function loadSpecialCandidates() {
    if (this.currentMode !== 'special') {
        return
    }

    const categoryId = this.specialCategorySelectTarget.value || ''

    if (!categoryId) {
        this.specialShowAllBtnTarget.style.display = 'none'
        this.specialStatusTarget.textContent =
            'Sélectionne une catégorie pour charger les émissions.'
        this.setEmissionsListHtml('')
        return
    }

    const search = this.hasSpecialSearchTarget
        ? this.specialSearchTarget.value.trim()
        : ''

    this.specialStatusTarget.textContent = 'Chargement des émissions…'
    this.setEmissionsListHtml('<div>Chargement…</div>')

    try {
        const params = new URLSearchParams({
            categoryId,
            all: '0'
        })

        if (search.length >= 3) {
            params.set('q', search)
        }

        const data = await getJson(
            `/admin/grille/special-candidates?${params.toString()}`
        )

        this.renderSpecialEmissions(data, false)
    } catch (error) {
        this.specialShowAllBtnTarget.style.display = 'none'
        this.specialStatusTarget.textContent =
            'Impossible de charger les émissions.'
        this.setEmissionsListHtml('<div>Impossible de charger les émissions.</div>')
    }
}

