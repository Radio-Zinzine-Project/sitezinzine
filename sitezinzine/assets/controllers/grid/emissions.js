export async function loadCandidatesForSelectedPostit() {
    if (!this.selectedPostit) {
        this.setEmissionsListHtml('<div>Aucune émission compatible pour le moment.</div>')
        return
    }

    const { slotId, startsAt } = getSlotData(this.selectedPostit)

    const assignedEmissionTitle =
        this.selectedPostit.dataset.assignedEmissionTitle || ''

    const broadcastRank =
        parseInt(this.selectedPostit.dataset.broadcastRank || '1', 10)

    if (!slotId || !startsAt) {
        this.setEmissionsListHtml('<div>Impossible de charger les émissions.</div>')
        return
    }

    const search = this.hasRegularSearchTarget
        ? this.regularSearchTarget.value.trim()
        : ''

    const categoryId = (
        this.regularOtherCategory &&
        this.hasRegularCategorySelectTarget
    )
        ? this.regularCategorySelectTarget.value
        : ''

    this.setEmissionsListHtml('<div>Chargement…</div>')

    try {
        const params = new URLSearchParams({
            slotId,
            startsAt,
            extended: this.regularExtended ? '1' : '0'
        })

        if (categoryId) {
            params.set('categoryId', categoryId)
        }

        if (search.length >= 3) {
            params.set('q', search)
        }

        const data = await getJson(`/admin/grille/candidates?${params.toString()}`)

        const items = Array.isArray(data.items) ? data.items : []
        const hasAutoGeneratedCandidate = items.some((item) => item.isAutoGenerated === true)

        this.renderEmissions(data, {
            showCreateLive: !categoryId &&
                !assignedEmissionTitle &&
                broadcastRank === 1 &&
                !hasAutoGeneratedCandidate
        })
    } catch (error) {
        this.setEmissionsListHtml('<div>Impossible de charger les émissions.</div>')
    }
}

export async function selectEmission(event) {
    const card = event.currentTarget
    const emissionId = card.dataset.emissionId
    const emissionsList = this.getCurrentEmissionsListTarget()

    if (this.currentMode === 'special') {
        return
    }

    const { slotId, startsAt } = getSlotData(this.selectedPostit)

    if (!slotId || !startsAt || !emissionId) {
        alert('Informations incomplètes pour affecter cette émission.')
        return
    }

    /*
     * Un créneau annulé ou l'origine d'un créneau déplacé est affiché
     * comme une projection/restauration dans la grille.
     *
     * Si on lui affecte une émission, une simple mise à jour du post-it
     * dans le DOM ne suffit pas : il faut reconstruire la grille depuis
     * l'état serveur après l'affectation.
     */
    const requiresGridReload =
        this.selectedPostit.dataset.isCancelled === 'true' ||
        this.selectedPostit.dataset.isRescheduledOrigin === 'true'

    try {
        const data = await postForm('/admin/grille/assign', {
            slotId,
            emissionId,
            startsAt
        })

        /*
         * Comportement existant :
         * une propagation nécessite déjà un rechargement complet.
         *
         * On ajoute uniquement les occurrences annulées/déplacées,
         * dont la représentation projetée doit également être reconstruite.
         */
        if (data.propagated === true || requiresGridReload) {
            this.saveScrollTarget(startsAt)
            window.location.reload()
            return
        }

        if (data.emissionCategoryTitle) {
            this.selectedPostit.dataset.categoryTitle =
                data.emissionCategoryTitle
        }

        if (data.emissionCategorySlug) {
            this.selectedPostit.dataset.categorySlug =
                data.emissionCategorySlug
        }

        await updateAssignedPostit(
            this,
            emissionId,
            data.emissionTitle,
            false
        )

        this.slotSummaryTarget.innerHTML =
            this.buildSlotSummary(
                this.selectedPostit,
                data.emissionTitle
            )

        this.clearRegularSearch()

        if (emissionsList) {
            emissionsList
                .querySelectorAll('.emission-card')
                .forEach((el) => el.classList.remove('is-selected'))
        }

        card.classList.add('is-selected')

    } catch (error) {
        alert(
            error.message ||
            'Erreur lors de l’affectation de l’émission.'
        )
    }
}

export async function createLiveEmission() {
    if (!this.selectedPostit || this.selectedPostit.dataset.slotLocked === 'true') {
        return
    }

    if (this.currentMode !== 'regular') {
        return
    }

    const { slotId, startsAt } = getSlotData(this.selectedPostit)

    if (!slotId || !startsAt) {
        alert('Informations incomplètes pour créer ce direct.')
        return
    }

    try {
        const data = await postForm('/admin/grille/create-live', {
            slotId,
            startsAt
        })

        if (data.propagated === true) {
            this.saveScrollTarget(startsAt)
            window.location.reload()
            return
        }

        await updateAssignedPostit(
            this,
            data.emissionId,
            data.emissionTitle,
            true
        )

    } catch (error) {
        console.error(error)

        alert(
            `Erreur lors de la création du direct : ${error.message}`
        )
    }
}


export function renderEmissions(
    context,
    data,
    {
        showCreateLive = false
    } = {}
) {
    const items = Array.isArray(data.items) ? data.items : []

    let html = ''

    if (showCreateLive) {
        html += context.buildCreateLiveButton()
    }

    if (items.length === 0) {
        html += '<div>Aucune émission compatible pour le moment.</div>'
    } else {
        html += items.map((item) => `
        <div
            class="emission-card ${item.isAutoGenerated ? 'is-auto-generated' : ''}"
            data-emission-id="${item.id}"
            data-emission-title="${escapeHtml(item.title)}"
            data-emission-duration="${parseInt(item.durationMinutes || 0, 10) || 0}"
            data-action="click->grid#selectEmission"
        >
            ${escapeHtml(item.title)}
            <small>
                ${escapeHtml(item.meta ?? '')}
                ${item.isAutoGenerated ? ' • direct' : ''}
            </small>
        </div>
    `).join('')
    }

    if (showCreateLive) {
        html += context.buildCreateLiveButton()
    }

    context.setEmissionsListHtml(html)
}

export function renderSpecialEmissions(
    context,
    data,
    allLoaded = false
) {
    const items = Array.isArray(data.items) ? data.items : []
    const categoryId = context.specialCategorySelectTarget.value || ''

    let html = ''

    if (categoryId) {
        html += `
            <div
                class="emission-card is-live-proxy"
                data-source="pool"
                data-special-item-type="manual_live"
                data-category-id="${escapeHtml(categoryId)}"
                data-emission-duration="60"
            >
                Créer un direct
                <small>Glisse cette carte dans la grille</small>
            </div>
        `
    }

    if (items.length === 0) {
        html += '<div>Aucune émission trouvée pour cette catégorie.</div>'
    } else {
        html += items.map((item) => `
            <div
                class="emission-card"
                data-source="pool"
                data-special-item-type="manual_emission"
                data-emission-id="${item.id}"
                data-emission-title="${escapeHtml(item.title)}"
                data-emission-duration="${parseInt(item.durationMinutes || 0, 10) || 0}"
            >
                ${escapeHtml(item.title)}
                <small>
                    ${escapeHtml(item.meta ?? '')}
                    ${item.playLabel ? ` • ${escapeHtml(item.playLabel)}` : ''}
                </small>
            </div>
        `).join('')
    }

    context.setEmissionsListHtml(html)

    const emissionsList = context.getCurrentEmissionsListTarget()

    if (emissionsList) {
        emissionsList.querySelectorAll('.emission-card').forEach((card) => {
            context.makeDraggable(card, 'pool')
        })
    }

    const total = parseInt(data.total || items.length || 0, 10)
    const hasMore = data.hasMore === true && allLoaded === false

    context.specialShowAllBtnTarget.style.display = hasMore ? 'block' : 'none'
    context.specialStatusTarget.textContent =
        `${total} émission(s) disponible(s). Glisse une carte dans la grille.`
}

export async function removeAssignment() {
    if (!this.selectedPostit || this.selectedPostit.dataset.slotLocked === 'true') {
        return
    }

    if (this.currentMode !== 'regular') {
        return
    }

    const { slotId, startsAt } = getSlotData(this.selectedPostit)

    if (!slotId || !startsAt) {
        alert('Informations incomplètes pour retirer cette émission.')
        return
    }

    const title =
        this.selectedPostit.dataset.assignedEmissionTitle ||
        'Émission inconnue'

    const broadcastRank =
        parseInt(this.selectedPostit.dataset.broadcastRank || '1', 10)

    let message = ''

    if (broadcastRank === 1) {
        message =
            `Retirer cette émission de la grille ?\n\n` +
            `Émission : ${title}\n` +
            `Première diffusion : ${startsAt}\n\n` +
            `Les rediffusions liées à cette programmation seront aussi retirées.\n\n` +
            `L’émission elle-même ne sera pas supprimée.`
    } else {
        message =
            `Retirer cette rediffusion de la grille ?\n\n` +
            `Émission : ${title}\n` +
            `Rediffusion : ${startsAt}\n\n` +
            `L’émission elle-même ne sera pas supprimée.`
    }

    const confirmed = window.confirm(message)

    if (!confirmed) {
        return
    }

    try {
        const data = await postForm('/admin/grille/remove', {
            slotId,
            startsAt
        })

        if (data.propagated === true) {
            this.saveScrollTarget(startsAt)
            window.location.reload()
            return
        }

        this.selectedPostit.dataset.emissionIsAutoGenerated = 'false'
        this.selectedPostit.dataset.assignedEmissionId = ''
        this.selectedPostit.dataset.assignedEmissionTitle = ''
        this.selectedPostit.classList.remove('assigned')

        this.renderPostitContent(this.selectedPostit)

        this.slotSummaryTarget.innerHTML =
            this.buildSlotSummary(this.selectedPostit)

        this.slotActionsTarget.style.display = 'none'

        await this.loadCandidatesForSelectedPostit()

    } catch (error) {
        alert(
            error.message ||
            'Erreur lors de la suppression de l’émission.'
        )
    }
}

export function clearRegularSearch() {
    if (this.hasRegularSearchTarget) {
        this.regularSearchTarget.value = ''
    }

    this.regularExtended = false
}

export function clearSpecialSearch() {
    if (this.hasSpecialSearchTarget) {
        this.specialSearchTarget.value = ''
    }
}